#!/usr/bin/env python3
"""The two supplementary sweep tables, generated instead of typed.

WHY. Twelve of the manuscript's forty-nine waived numbers were the cells of these two
tables, and the ledger calls a waiver unbound debt rather than an exemption. Both tables
are fully backed: the budget sweep by one result file per arm per budget plus a summary
carrying the per-seed values, the cut curve by one result file per arm per cut plus the
run logs, which are where the retained-row counts and the refusal reasons live.

WHAT GENERATING THEM BUYS BEYOND THE WAIVERS. Two independent paths reach the control's
value at each budget, the summary's own `control` block and the per-arm result file, and
this refuses if they disagree. The hand-typed table could not notice that. The cut curve
gains the same: its unrestricted row must reproduce the frozen primaries from the arm
table, which is a different artifact produced by a different run.

AND IT REMOVES A LITERAL COLLISION. The ledger keys on the printed string, so a waiver
written for one quantity exempts every occurrence of that string. `0.0416` is the donor
architecture's seed spread at one budget in the supplement AND the composition's gain
over its member in the Results, and one waiver was covering both. Generated files are
skipped by the sweep, so binding the supplement's occurrence leaves the Results one to
be checked on its own.
"""

from __future__ import annotations

import argparse
import json
import re
import statistics
from pathlib import Path

CUTS = (54, 60, 70, 80, 90, 100)
ARMS = (("persistence_seed17", "Control"), ("balanced_lstm_erm_seed17", "LSTM"))
TOLERANCE = 5e-5


def primary(path: Path) -> float:
    payload = json.loads(path.read_text())
    value = payload.get("primary_equal_horizon_mean_event_sensitivity")
    if isinstance(value, dict):
        value = value["global"]
    return float(value)


def holm(raw: list[float]) -> list[float]:
    order = sorted(range(len(raw)), key=lambda i: raw[i])
    out, running = [0.0] * len(raw), 0.0
    for rank, index in enumerate(order):
        running = max(running, (len(raw) - rank) * raw[index])
        out[index] = min(running, 1.0)
    return out


def _sweep_cell(directory: Path, stem: str, budget: str) -> float:
    """The fapd-sweep filenames are not consistently formatted across arms."""
    matches = sorted(directory.glob(f"{stem}-fapd*.json"))
    for path in matches:
        tag = path.stem.split("-fapd", 1)[1]
        if abs(float(tag) - float(budget)) < 1e-9:
            return primary(path)
    raise SystemExit(f"no {stem} cell at budget {budget}; found "
                     f"{[p.stem for p in matches]}")


def budget_table(sweep_dir: Path, summary_path: Path) -> tuple[str, int]:
    summary = json.loads(summary_path.read_text())
    budgets = sorted(summary["control"], key=float)
    raw_p = [float(summary["derived"][b]["p"]) for b in budgets]
    adjusted = holm(raw_p)

    rows = []
    for index, budget in enumerate(budgets):
        block = summary["derived"][budget]
        control = float(summary["control"][budget])
        # Two artifacts, one number. The hand-typed table could not check this.
        from_file = _sweep_cell(sweep_dir, "persistence_seed17", budget)
        if abs(control - from_file) > TOLERANCE:
            raise SystemExit(
                f"budget {budget}: the summary says the control is {control} "
                f"and its own result file says {from_file}"
            )
        per_seed = summary["per_seed"][budget]
        mean = statistics.mean(float(v) for v in per_seed.values())
        if abs(mean - float(block["mean"])) > TOLERANCE:
            raise SystemExit(
                f"budget {budget}: the mean {block['mean']} is not the mean "
                f"of its own per-seed values, {mean}"
            )
        tcn = _sweep_cell(sweep_dir, "tcn_erm_seed17", budget)
        # The t column was added 2026-09-06. The Nature Portfolio Reporting Summary
        # asks for "the test statistic ... with confidence intervals, effect sizes,
        # degrees of freedom and P value noted", and t was the one item of that list
        # living nowhere in the manuscript. It was found by cross-checking the journal
        # pack's numbers against the body: the pack quoted a t the body never printed.
        rows.append(
            f"{budget} & {control:.4f} & {tcn:.4f} & {mean:.4f} & "
            f"{float(block['sd']):.4f} & ${float(block['margin']):+.4f}$ & "
            f"${float(block['t']):.3f}$ & ${adjusted[index]:.3f}$ \\\\"
        )

    body = "\n".join([
        "% Generated by code/scripts/figures/build_sweep_tables.py. "
        "Do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering",
        r"{\small\setlength{\tabcolsep}{4.5pt}",
        r"\begin{tabular}{lrrrrrrr}",
        r"\toprule",
        r"\shortstack{Nominal budget\\(FA/day)} & Control & TCN & LSTM & SD & Margin & "
        r"$t$ & $P$ \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}}",
        r"\caption{Primary endpoint sensitivity across nominal false-alarm budgets, "
        r"expressed as false alarms per participant-day (FA/day). Each sensitivity is "
        r"averaged over event-positive participants within source, equally over the "
        r"eleven "
        r"sources, and equally over the 30- and 60-minute horizons on the selection "
        r"partition. Higher values are better. Thresholds are refitted on the "
        r"calibration "
        r"partition at each nominal budget. The source-balanced long short-term memory "
        r"network (LSTM) column reports the mean across five training seeds, with "
        r"their "
        r"empirical standard deviation (SD). The current-glucose control is "
        r"deterministic, "
        r"and the temporal convolutional network (TCN) is a single trained fit. "
        r"\emph{Margin} is control minus the five-seed LSTM mean, so positive values "
        r"favour the control. The two-sided one-sample $t$-test uses four degrees of "
        r"freedom and measures training-seed variation on a fixed participant split, "
        r"rather than participant-sampling uncertainty. Reported $P$ values are "
        r"Holm-adjusted across the five-budget test family. No test against the TCN is "
        r"reported because its multiseed variability was not measured under the "
        r"current "
        r"checkpoint proxy.}",
        r"\label{tab:budget_sweep}",
        r"\end{table}",
        "",
    ])
    return body, len(rows)


def _cut_paths(cut_dir: Path, eugly_dir: Path, cut: int,
               stem: str) -> tuple[Path, Path]:
    """Cut 70 is the euglycaemic restriction and its run lives in its own directory.

    The two were produced by different scripts on different days and were never merged.
    Hard-coding one directory silently dropped the row the whole section is about.
    """
    if cut == 70:
        return eugly_dir / f"{stem}.json", eugly_dir / f"{stem}.log"
    return cut_dir / f"{stem}_cut{cut}.json", cut_dir / f"{stem}_cut{cut}.log"


def cut_table(cut_dir: Path, eugly_dir: Path, arm_table: Path) -> tuple[str, int, int]:
    frozen = {r["arm"]: float(r["primary"])
              for r in json.loads(arm_table.read_text())["rows"]}
    retained = {}
    refused = {}
    for cut in CUTS:
        _json, log = _cut_paths(cut_dir, eugly_dir, cut, "persistence_seed17")
        if not log.is_file():
            raise SystemExit(
                f"{log.name} is missing; the retained-row share lives there")
        text = log.read_text()
        share = re.search(
            r"cgm_last >= [\d.]+: [\d,]+ of [\d,]+ rows \(([\d.]+)%\)", text)
        if share is None:
            raise SystemExit(f"{log.name} carries no retained-row line")
        retained[cut] = float(share.group(1))
        why = re.search(
            r"ValueError: (source has no event-positive participant: .+)", text)
        if why:
            refused[cut] = why.group(1).strip()

    rows = [f"none & 100.00\\% & {frozen['persistence_seed17']:.4f} & "
            f"{frozen['balanced_lstm_erm_seed17']:.4f} & control \\\\"]
    evaluated = 0
    for cut in CUTS:
        if cut in refused:
            rows.append(f"{cut} & {retained[cut]:.2f}\\% & "
                        r"\multicolumn{3}{l}{refused by the estimand} \\")
            continue
        values = {}
        for stem, _label in ARMS:
            path, _log = _cut_paths(cut_dir, eugly_dir, cut, stem)
            if not path.is_file():
                raise SystemExit(f"{path.name} is missing and the cut was not refused")
            values[stem] = primary(path)
        evaluated += 1
        leader = "control" if values["persistence_seed17"] >\
            values["balanced_lstm_erm_seed17"] else "LSTM"
        rows.append(
            f"{cut} & {retained[cut]:.2f}\\% & {values['persistence_seed17']:.4f} & "
            f"{values['balanced_lstm_erm_seed17']:.4f} & {leader} \\\\")

    if not refused:
        raise SystemExit(
            "no cut was refused; the caption says the strictest ones are, and a table "
            "that quietly reports them would be the defect this column exists to show")
    body = "\n".join([
        "% Generated by code/scripts/figures/build_sweep_tables.py. "
        "Do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering",
        r"{\small\setlength{\tabcolsep}{5pt}",
        r"\begin{tabular}{lrrrl}",
        r"\toprule",
        r"Cut (mg/dL) & Rows retained & Control & LSTM & Leader \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}}",
        r"\caption{Primary endpoint sensitivity against the minimum current-glucose "
        r"eligibility cut-off. At each cut-off, decisions with current glucose at or "
        r"above "
        r"the stated value are retained, alarm thresholds are refitted on the "
        r"restricted "
        r"calibration partition at a nominal 0.5 false alarms per participant-day, and "
        r"sensitivity is evaluated on the corresponding restricted selection partition "
        r"after excluding active level 2 events. Sensitivity is averaged over "
        r"event-positive "
        r"participants within source, equally over the eleven sources and equally over "
        r"the 30- and 60-minute horizons. Higher values are better. Control denotes "
        r"the "
        r"current-glucose rule and LSTM the source-balanced long short-term memory "
        r"network, evaluated at the registered training seed. \emph{Rows retained} "
        r"reports the percentage of all 11{,}759{,}997 scored calibration and "
        r"selection "
        r"rows surviving each restriction, before active-event exclusions. It does not "
        r"describe the eligible selection population alone. \emph{Leader} identifies "
        r"the larger point estimate without implying statistical superiority. The "
        r"unrestricted row reproduces the frozen primary values. Cut-offs above "
        r"70~mg/dL "
        r"are refused rather than reported as zero because the smallest "
        r"development cohort retains no event-positive selection participant.}",
        r"\label{tab:cut_curve}",
        r"\end{table}",
        "",
    ])
    return body, evaluated, len(refused)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fapd-sweep", required=True, type=Path)
    parser.add_argument("--budget-summary", required=True, type=Path)
    parser.add_argument("--cutcurve", required=True, type=Path)
    parser.add_argument("--euglycaemic", required=True, type=Path,
                        help="cut 70 was run separately and lives here")
    parser.add_argument("--arm-table", required=True, type=Path)
    parser.add_argument("--out-dir", required=True, type=Path)
    arguments = parser.parse_args(argv)

    budget, n_budgets = budget_table(arguments.fapd_sweep, arguments.budget_summary)
    cuts, evaluated, refused = cut_table(
        arguments.cutcurve, arguments.euglycaemic, arguments.arm_table)
    arguments.out_dir.mkdir(parents=True, exist_ok=True)
    (arguments.out_dir / "tab_budget_sweep.tex").write_text(budget)
    (arguments.out_dir / "tab_cut_curve.tex").write_text(cuts)
    print(f"wrote tab_budget_sweep.tex  {n_budgets} budgets, control cross-checked "
          f"against its own result file at each")
    print(f"wrote tab_cut_curve.tex     {evaluated} cuts evaluated, {refused} refused "
          f"by the estimand, refusal read from the run that raised it")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
