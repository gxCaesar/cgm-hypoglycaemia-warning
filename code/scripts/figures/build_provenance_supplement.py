#!/usr/bin/env python3
'Build provenance supplement.'

























from __future__ import annotations

import argparse
import datetime as _dt
import re
from pathlib import Path

PACKAGES = ("torch", "numpy", "pandas", "scikit-learn", "pyarrow")
LABEL = {"torch": "PyTorch", "numpy": "NumPy", "pandas": "pandas",
         "scikit-learn": "scikit-learn", "pyarrow": "PyArrow"}


def versions(text: str) -> dict[str, str]:
    """Both recorded formats, `name x.y.z` per line and `name=x.y.z` inline."""
    found: dict[str, str] = {}
    for package in PACKAGES:
        m = (re.search(rf"(?m)^{re.escape(package)}\s+([0-9][0-9.]*)", text)
             or re.search(rf"{re.escape(package)}=([0-9][0-9.]*)", text))
        if m:
            found[package] = m.group(1)
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--env", action="append", required=True,
                        help="label=path/to/env.txt, repeatable")
    parser.add_argument("--seed-dir", type=Path,
                        help="directory of per-seed result files, one per fit")
    parser.add_argument("--output", required=True, type=Path)
    arguments = parser.parse_args(argv)

    records = []
    for item in arguments.env:
        label, _, path = item.partition("=")
        text = Path(path).read_text()
        found = versions(text)
        if not found:
            raise SystemExit(f"{label}: no package versions found in {path}")
        records.append((label, text, found))

    shared = set.intersection(*(set(f) for _l, _t, f in records))
    if not shared:
        raise SystemExit("the environment records share no package, so no table can "
                         "describe them both")
    for package in sorted(shared):
        seen = {label: found[package] for label, _t, found in records}
        if len(set(seen.values())) != 1:
            raise SystemExit(
                f"{package} differs between recorded environments ({seen}); this table "
                "quotes one version per package and must not be built "
                "from records that disagree"
            )
    # Union, not intersection. Restricting to the shared set dropped scikit-learn, which
    # only one record carries and which is the library whose version change moved a
    # baseline here by 0.031 to 0.076 -- the most decision-relevant row in the table.
    covered: dict[str, str] = {}
    for _label, _text, found in records:
        covered.update(found)
    partial = sorted(set(covered) - shared)

    # The caption said "nine days apart" when the records are fourteen, and printed the
    # record count where a host count belonged. Both are computed now.
    stamps = []
    for _label, text, _found in records:
        m = re.search(r"(20\d\d-\d\d-\d\d)T", text)
        if not m:
            raise SystemExit(f"{_label}: no timestamp in the environment record")
        stamps.append(_dt.date.fromisoformat(m.group(1)))
    apart = (max(stamps) - min(stamps)).days
    hosts = set()
    for _label, text, _found in records:
        m = re.search(r"host[=:]\s*(\S+)", text)
        if m:
            hosts.add(m.group(1))

    python = re.search(r"(?m)^python\s+([0-9][0-9.]*)", records[0][1])
    cuda = re.search(r"cuda\s+([0-9][0-9.]*)", records[0][1])

    rows = []
    if python:
        rows.append(("Python", python.group(1)))
    for package in PACKAGES:
        if package in covered:
            value = covered[package]
            if package == "torch" and cuda:
                value += f" (CUDA {cuda.group(1)})"
            rows.append((LABEL[package], value))

    # Read the seeds off the artifacts rather than typing them. Five integers are easy
    # to type and easy to get wrong once the set changes.
    seed_note = ""
    if arguments.seed_dir:
        seeds = sorted(
            int(m.group(1))
            for path in arguments.seed_dir.glob("*seed*.json")
            for m in [re.search(r"seed0*([0-9]+)", path.stem)] if m
        )
        if not seeds:
            raise SystemExit(f"no per-seed artifacts under {arguments.seed_dir}")
        seed_note = (f"The {len(seeds)} fits that quantify run-to-run variability use "
                     f"training seeds {', '.join(str(s) for s in seeds[:-1])} and "
                     f"{seeds[-1]} under this software stack. ")

    partial_note = ""
    if partial:
        package_labels = ", ".join("\\texttt{" + LABEL[q] + "}" for q in partial)
        partial_note = f", with {package_labels} appearing in one record"

    body = [
        "% Generated by code/scripts/figures/build_provenance_supplement.py. "
        "Do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering",
        r"{\footnotesize",
        r"\begin{tabular}{ll}",
        r"\toprule",
        r"Component & Version \\",
        r"\midrule",
    ]
    body += [f"{name} & {value} " + r"\\" for name, value in rows]
    body += [
        r"\bottomrule",
        r"\end{tabular}}",
        r"\caption{Software environment versions recorded for the reported multiseed "
        r"runs. The "
        + f"{len(records)} environment records retained by this study, captured on "
        + f"{len(hosts)} hosts {apart} days apart, match identically on every shared "
        + "package" + partial_note + ". " + seed_note +
        r"The earlier campaign that produced the frozen single-seed comparator "
        r"artefacts retained no environment manifest of its own, a distinction noted "
        r"because identical code on identical splits shifted a baseline by between "
        r"$0.031$ and $0.076$ across two releases of \texttt{scikit-learn}.}",
        r"\label{tab:provenance}",
        r"\end{table}",
        "",
    ]
    # The closing sentence names a library. If it is not a row, the sentence is false,
    # which it silently was on the first build when the table used the shared set.
    if "scikit-learn" not in covered:
        raise SystemExit(
            "the caption's closing sentence is about scikit-learn and no record "
            "carries its version, so the sentence would not describe this table"
        )
    arguments.output.write_text("\n".join(body))
    print(f"wrote {arguments.output}  {seed_note}{len(rows)} components from "
          f"{len(records)} environment records; "
          f"shared packages agree: {sorted(shared)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
