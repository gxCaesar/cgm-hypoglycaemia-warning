#!/usr/bin/env python3
"""Render population tables from source-level warning-analysis aggregates."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

SOURCE_ORDER = (
    "CTR3",
    "DCLP3",
    "DCLP5",
    "Flair",
    "IOBP2",
    "PEDAP",
    "ReplaceBG",
    "AZT1D",
    "BrisT1D",
    "Shanghai T1DM",
    "T1D-UOM",
)
ROLES = ("train", "selection", "calibration")
ROLE_LABELS = {
    "train": "Training",
    "selection": "Selection",
    "calibration": "Calibration",
}


def integer(value) -> str:
    if pd.isna(value) or value < 0 or int(value) != value:
        raise ValueError("table counts must be nonnegative integers")
    return f"{int(value):,}"


def table(rows, columns, header, caption, label):
    return "\n".join(
        [
            "% Generated by code/scripts/build_revision_population_tables.py.",
            r"\begin{table}[!htbp]",
            r"\centering",
            r"{\footnotesize\setlength{\tabcolsep}{3.2pt}",
            r"\begin{tabular}{" + columns + "}",
            r"\toprule",
            header,
            r"\midrule",
            *rows,
            r"\bottomrule",
            r"\end{tabular}}",
            r"\caption{" + caption + "}",
            r"\label{" + label + "}",
            r"\end{table}",
            "",
        ]
    )


def build(aggregate: Path, output: Path):
    summary = json.loads((aggregate / "population-summary.json").read_text())
    if (
        summary["status"] != "passed"
        or summary["timeline_counts"]["status"] != "passed"
    ):
        raise ValueError("complete endpoint and timeline reporting is required")
    inputs = pd.read_csv(aggregate / "input-counts.csv")
    endpoints = pd.read_csv(aggregate / "endpoint-counts.csv")
    windows = pd.read_csv(aggregate / "training-window-counts.csv")
    if set(inputs.source_id) != set(SOURCE_ORDER) or len(inputs) != 33:
        raise ValueError("population source/partition grid differs from the study")
    if set(inputs.partition) != set(ROLES):
        raise ValueError("population partitions differ from the study")
    input_index = inputs.set_index(["source_id", "partition"], verify_integrity=True)
    if int(inputs.participants.sum()) != summary["original_participants"]:
        raise ValueError("participant count disagrees with aggregate summary")
    source_endpoints = endpoints.loc[endpoints.row_type == "source"]
    source_60 = source_endpoints.loc[source_endpoints.horizon == 60]
    cohort = source_60.groupby("source_id", observed=True).sum(numeric_only=True)
    event_30 = (
        source_endpoints.loc[source_endpoints.horizon == 30]
        .groupby("source_id", observed=True)
        .base_events.sum()
    )
    cohort["events_30"] = event_30
    counts = inputs.groupby("source_id", observed=True).participants.sum()
    if not cohort.base_participants.eq(counts).all():
        raise ValueError("cohort participants disagree with input counts")
    cohort_rows, split_rows, plot_data = [], [], {}
    for source in SOURCE_ORDER:
        row = cohort.loc[source]
        cohort_rows.append(
            source
            + " & "
            + " & ".join(
                integer(row[k])
                for k in (
                    "base_participants",
                    "calendar_days",
                    "events_30",
                    "base_events",
                )
            )
            + r" \\"
        )
        values = [input_index.loc[source, role] for role in ROLES]
        split_rows.append(
            source
            + " & "
            + " & ".join(integer(v.participants) for v in values)
            + " & "
            + integer(sum(v.participants for v in values))
            + " & "
            + integer(sum(v.base_evaluable_decisions for v in values))
            + r" \\"
        )
        plot_data[source] = {
            "participants": int(row.base_participants),
            "person_days": int(row.calendar_days),
            "severe_hypo_events": int(row.base_events),
            "severe_hypo_events_30": int(row.events_30),
        }
    totals = cohort.sum(numeric_only=True)
    cohort_rows += [
        r"\midrule",
        "All development & "
        + " & ".join(
            integer(totals[k])
            for k in ("base_participants", "calendar_days", "events_30", "base_events")
        )
        + r" \\",
    ]
    split_rows += [
        r"\midrule",
        "All development & "
        + " & ".join(
            integer(inputs.loc[inputs.partition == role, "participants"].sum())
            for role in ROLES
        )
        + " & "
        + integer(inputs.participants.sum())
        + " & "
        + integer(inputs.base_evaluable_decisions.sum())
        + r" \\",
    ]
    role_events = endpoints.loc[endpoints.row_type == "role_total"].set_index(
        ["partition", "horizon"], verify_integrity=True
    )
    role_windows = windows.loc[windows.row_type == "role_total"].set_index(
        ["partition", "horizon"], verify_integrity=True
    )
    target_rows = []
    for role in ROLES:
        for horizon in (30, 60):
            e, w = role_events.loc[role, horizon], role_windows.loc[role, horizon]
            if (
                w.base_evaluable_decisions
                != inputs.loc[
                    inputs.partition == role, "base_evaluable_decisions"
                ].sum()
            ):
                raise ValueError("base windows disagree between aggregate tables")
            target_rows.append(
                ROLE_LABELS[role]
                + f" & {horizon} & "
                + " & ".join(
                    integer(v)
                    for v in (
                        w.base_evaluable_decisions,
                        w.retained_training_windows,
                        w.positive_training_windows,
                        e.base_events,
                        e.event_positive_participants,
                        e.calendar_days,
                    )
                )
                + r" \\"
            )
    payload = {
        "tab_cgm_cohort.tex": table(
            cohort_rows,
            "lrrrr",
            r"Source & Participants & Calendar days & Events, 30 min & Events, 60 "
            r"min \\",
            "Development-cohort composition and CGM-defined level 2 event "
            "denominators. "
            "CGM denotes continuous glucose monitoring. Counts sum "
            "participant-disjoint "
            "training, selection and calibration partitions. Events require at "
            "least three consecutive "
            "five-minute readings below 54 mg/dL and an evaluable lead-in at the "
            "indicated "
            "horizon. Episodes are merged across complete gaps of at most 30 minutes. "
            "Calendar days are distinct participant-day pairs represented by "
            "base-evaluable "
            "decisions. Event and exposure denominators remain fixed across "
            "current-glucose "
            "eligibility rules. External cohorts are not included.",
            "tab:cgm_cohort",
        ),
        "tab_split.tex": table(
            split_rows,
            "lrrrrr",
            r"Source & Training & Selection & Calibration & Total & Base windows \\",
            "Analysed development participants and base-evaluable decision windows. "
            "Participant assignments precede window construction. All 1,020 retained "
            "participants are included, with eight of the 1,028 enrolled participants "
            "excluded by data eligibility requirements. Window counts sum the three "
            "partitions before task-specific supervision masks or training "
            "subsampling. "
            "Each window supports the 30- and 60-minute horizons and has a complete "
            "60-minute future interval. A base window is distinct from an event "
            "and from "
            "an issued alarm.",
            "tab:split",
        ),
        "tab_endpoint_population.tex": table(
            target_rows,
            "lrrrrrrr",
            r"Partition & $h$ (min) & \shortstack{Base\\windows} & "
            r"\shortstack{Eligible\\windows} & "
            r"\shortstack{Positive\\windows} & \shortstack{Base\\events} & "
            r"\shortstack{Event-positive\\participants} & "
            r"\shortstack{Calendar\\days} \\",
            "Level 2 window labels, event counts and fixed exposure by partition and "
            "prediction horizon $h$. Eligible windows have an evaluable outcome and"
            " observed "
            "current glucose at or above 54 mg/dL, matching the hypoglycaemia "
            "supervision "
            "mask before negative subsampling. Positive windows contain a future "
            "level 2 "
            "onset within the corresponding horizon. Multiple windows may precede"
            " the same "
            "event. Base events and event-positive participants are counted "
            "independently "
            "of the current-glucose eligibility rule. Calendar days include all base "
            "participants, including those without an event. Counts are pooled totals "
            "across eleven sources, not source-macro averages.",
            "tab:endpoint_population",
        ),
    }
    output.mkdir(parents=True, exist_ok=True)
    for name, text in payload.items():
        (output / name).write_text(text)
    (output / "cohort-figure-counts.json").write_text(
        json.dumps(plot_data, indent=2) + "\n"
    )
    return {
        "participants": int(totals.base_participants),
        "calendar_days": int(totals.calendar_days),
        "events_30": int(totals.events_30),
        "events_60": int(totals.base_events),
        "base_windows": int(inputs.base_evaluable_decisions.sum()),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--aggregate", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(build(args.aggregate, args.output)))


if __name__ == "__main__":
    main()
