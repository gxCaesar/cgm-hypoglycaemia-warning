#!/usr/bin/env python3
"""Build the descriptive participant alarm-rate table from accepted aggregates."""

import argparse
import json
from pathlib import Path
from statistics import fmean

LABELS = {
    "persistence": "Current CGM",
    "linear": "Linear extrapolation",
    "summary_logistic": "Summary logistic",
    "xgboost": "XGBoost",
    "lstm": "LSTM",
    "tcn": "TCN",
    "composition": "Rank composition",
}
SEEDS = {17, 23, 42, 71, 101}
CAPTION = " ".join(
    """Participant distributions of evaluable delivered and unmatched alarms per
calendar day on the selection partition. Each condition retains all 153
participants, including the seven without base events, and weights participants
equally across all eleven sources. Rates divide each participant's total alarms
by that participant's fixed calendar-day exposure. Columns report the median
and interquartile range (IQR), followed by the 90th percentile and maximum of
unmatched-alarm rates. For LSTM, TCN and rank composition, the median,
quartiles and 90th percentile are arithmetic means of five fit-specific
quantiles, whereas the maximum is the largest participant rate across all five
fits. The remaining arms use a single fit or deterministic rule. These values
are descriptive participant-rate summaries rather than quantiles of daily
records or confidence intervals, and model seeds are not pooled as additional
participants. All thresholds are fitted on calibration data at the nominal
budget of 0.5 unmatched alarms per participant-calendar day, with the rank
composition evaluated under base eligibility only.""".splitlines()
)


def build(report):
    if (
        report["status"] != "complete"
        or report["conditions"] != 66
        or report["aggregate_rows"] != 792
    ):
        raise ValueError("complete accepted66-condition aggregate required")
    rows = [r for r in report["rows"] if r["source_id"] == "all_participants"]
    if len(rows) != 66:
        raise ValueError("all66 participant distributions required")
    lines = [
        r"% Generated by code/scripts/build_burden_distribution_table.py.",
        r"\begin{table}[p]",
        r"\centering",
        r"{\footnotesize\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{lrrrllll}",
        r"\toprule",
        r"Model & Cut & Horizon & Fits & Delivered & Unmatched & 90th & Maximum \\",
        r" & (mg/dL) & (min) & & Median (IQR) & Median (IQR) & percentile & \\",
        r"\midrule",
    ]
    receipt = []
    for arm, label in LABELS.items():
        for cut in (54,) if arm == "composition" else (54, 70):
            for horizon in (30, 60):
                group = [
                    r
                    for r in rows
                    if (r["arm"], r["glucose_cut"], r["horizon_minutes"])
                    == (arm, cut, horizon)
                ]
                expected = SEEDS if arm in ("lstm", "tcn", "composition") else {None}
                if {r["model_seed"] for r in group} != expected or len(group) != len(
                    expected
                ):
                    raise ValueError("fit identity/count differs")
                values, cells = [], []
                for rate in (
                    "delivered_alarms_per_patient_day",
                    "unmatched_alarms_per_patient_day",
                ):
                    median, q25, q75 = [
                        fmean(r[f"{rate}_{stat}"] for r in group)
                        for stat in ("median", "q25", "q75")
                    ]
                    values.extend((median, q25, q75))
                    cells.append(f"{median:.3f} ({q25:.3f}--{q75:.3f})")
                p90 = fmean(r["unmatched_alarms_per_patient_day_p90"] for r in group)
                maximum = max(
                    r["unmatched_alarms_per_patient_day_maximum"] for r in group
                )
                values.extend((p90, maximum))
                cells.extend((f"{p90:.3f}", f"{maximum:.3f}"))
                lines.append(
                    f"{label} & {cut} & {horizon} & {len(group)} & "
                    + " & ".join(cells)
                    + r" \\"
                )
                receipt.append(
                    {
                        "arm": arm,
                        "glucose_cut": cut,
                        "horizon_minutes": horizon,
                        "fit_count": len(group),
                        "values": values,
                        "rendered_cells": cells,
                    }
                )
    lines.extend(
        [
            r"\bottomrule",
            r"\end{tabular}}",
            r"\caption{" + CAPTION + "}",
            r"\label{tab:burden_distribution}",
            r"\end{table}",
            "",
        ]
    )
    return "\n".join(lines), receipt


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--aggregate", required=True, type=Path)
    parser.add_argument("--acceptance", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    args = parser.parse_args()
    accepted = json.loads(args.acceptance.read_text())
    stat = args.aggregate.stat()
    actual = {
        "path": str(args.aggregate.resolve()),
        "size_bytes": stat.st_size,
        "mtime_ns": stat.st_mtime_ns,
    }
    if (
        accepted.get("owner") != "primary"
        or accepted.get("status") != "accepted_for_reporting"
        or accepted["input_binding"] != actual
    ):
        raise ValueError("primary acceptance must bind the exact aggregate input")
    output = args.output_dir.resolve()
    if not output.is_relative_to(Path("/private/tmp")) or output.exists():
        raise ValueError("output must be a new directory under /private/tmp")
    text, rows = build(json.loads(args.aggregate.read_text()))
    output.mkdir()
    (output / "tab_burden_distribution.tex").write_text(text)
    (output / "table-data.json").write_text(
        json.dumps({"rows": rows, "input_binding": actual}, indent=2) + "\n"
    )
    print(
        json.dumps(
            {
                "rows": len(rows),
                "quantile_and_maximum_values": sum(len(r["values"]) for r in rows),
                "output": str(output),
            }
        )
    )


if __name__ == "__main__":
    main()
