#!/usr/bin/env python3
"""Build supplementary calibration, channel-coverage and partition-count tables.

Inputs are prepared aggregate analysis outputs. This script does not train models,
change participant partitions or access external cohort labels.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HEADER = "% Generated by code/scripts/build_supplement_tables.py. Do not edit by hand."
ARMS = (
    ("persistence_seed17", "Current glucose (control)"),
    ("tcn_erm_seed17", "Temporal convolution, ERM"),
    ("balanced_lstm_erm_seed17", "LSTM, source-balanced ERM"),
)
HORIZONS = ("30", "60")
CHANNEL_SHORT = {
    "Glucose": "Glucose", "Basal insulin": "Basal", "Bolus insulin": "Bolus",
    "Insulin, total": "Insulin", "Carbohydrate": "Carbs", "Meal label": "Meal",
    "Heart rate": "HR", "Steps": "Steps", "Energy expenditure": "Energy",
    "Skin temperature": "Skin T", "Ambient temperature": "Air T",
    "Electrodermal activity": "EDA", "Workout": "Workout",
}


def table(body: list[str], spec: str, head: str, caption: str, label: str,
          size: str = "footnotesize") -> str:
    """Render a standalone captioned TeX table from prepared aggregate values."""
    return "\n".join([
        HEADER, r"\begin{table}[t]", r"\centering",
        "{\\" + size + r"\setlength{\tabcolsep}{3.2pt}",
        r"\begin{tabular}{" + spec + "}", r"\toprule", head, r"\midrule",
        *body, r"\bottomrule", r"\end{tabular}}",
        r"\caption{" + caption + "}", r"\label{" + label + "}",
        r"\end{table}", "",
    ])


def quality(calibration: Path) -> str:
    rows = []
    for arm, label in ARMS:
        payload = json.loads((calibration / f"{arm}.json").read_text())
        for horizon in HORIZONS:
            block = payload["horizons"][horizon]
            counts = block["participant_firing_counts"]
            rows.append(
                f"{label} & {horizon} & {block['brier']:.4f} & "
                f"{block['expected_calibration_error']:.4f} & "
                f"{block['calibration_slope']:.3f} & "
                f"{block['calibration_intercept']:+.3f} & "
                f"{block['median_lead_minutes']:g} & "
                f"{counts['median']:,.0f} & {counts['p90']:,.0f} & "
                f"{counts['max']:,.0f} & "
                f"{100 * counts['share_of_firings_in_top_decile']:.1f} \\\\"
            )
    head = (r"Arm & $h$ (min) & Brier & ECE & Slope & Intercept & Lead & Median & "
            r"p90 & Max & Top 15 (\%) \\")
    caption = (
        "Probability calibration, warning lead time and threshold-crossing "
        "concentration "
        "on the unrestricted selection partition for the current-glucose control "
        "and the two frozen seed-17 trained comparators. "
        "The analysis includes 5{,}952{,}251 windows from 153 participants after "
        "excluding "
        "windows inside active level 2 events. $h$ denotes the prediction horizon in "
        "minutes. Brier score, expected calibration error (ECE), and logistic "
        "calibration "
        "slope and intercept are computed over windows. Lower Brier score and ECE are "
        "better. Ideal slope and intercept are 1 and 0. \\emph{Lead} is median warning "
        "time in minutes among matched events after the 30-minute alarm refractory "
        "rule. "
        "\\emph{Median}, \\emph{p90} and \\emph{Max} summarise each participant's "
        "count "
        "of threshold-positive five-minute windows before refractory collapse, rather "
        "than distinct triggered alarms. \\emph{Top 15} is the percentage of these "
        "threshold-positive windows contributed by the 15 participants with the "
        "highest "
        "counts, approximately one tenth of the 153 participants. Counts span each "
        "participant's observed follow-up and are not daily rates. The control's "
        "crossing "
        "distribution is identical across horizons because both thresholds invert to "
        "the "
        "same current-glucose value. ERM, empirical risk minimisation; LSTM, long "
        "short-term memory network."
    )
    return table(rows, "llrrrrrrrrr", head, caption, "tab:quality")


def coverage(profile: Path) -> str:
    payload = json.loads(profile.read_text())
    sources = list(payload["sources"])
    rows = [
        "Enrolled $n$ & " + " & ".join(
            str(payload["sources"][source]["participants"]) for source in sources
        ) + r" \\",
        r"\midrule",
    ]
    for channel in payload["channels"]:
        cells = []
        for source in sources:
            block = payload["sources"][source]
            recorded = block["channel_participants"][channel]
            enrolled = block["participants"]
            share = 100.0 * recorded / enrolled
            cells.append("--" if recorded == 0 else
                         "100" if recorded == enrolled else f"{share:.1f}")
        rows.append(f"{CHANNEL_SHORT[channel]} & " + " & ".join(cells) + r" \\")
    head = ("Channel & " + " & ".join(
        s.replace("Shanghai T1DM", "Shang.").replace("ReplaceBG", "Repl.")
        for s in sources) + r" \\")
    caption = (
        "Participant-level channel availability in the eleven development sources, "
        "counted from the raw consolidated release for development sources only. "
        "The first numerical row gives each source's enrolled participant "
        "denominator. All remaining cells are percentages of those participants for "
        "whom "
        "a channel is ever recorded. Partial coverage is shown to one decimal place, "
        "and 100 denotes exact full coverage. These denominators include "
        "participants without eligible modelling windows. En-dashes denote exact zero "
        "coverage, rather than missing or inapplicable values. Basal and bolus denote "
        "the "
        "corresponding insulin channels. Insulin denotes total insulin; Carbs, "
        "carbohydrate; "
        "Meal, meal label; HR, heart rate; Energy, energy expenditure; Skin T, skin "
        "temperature; Air T, ambient temperature; EDA, electrodermal activity. Repl. "
        "and "
        "Shang. denote ReplaceBG and Shanghai T1DM."
    )
    return table(rows, "l" + "r" * len(sources), head, caption, "tab:coverage",
                 size="scriptsize")


SPLIT_TOTALS: dict[str, int] = {}


def split(profile: Path, manifest: Path, normalized: Path) -> str:
    """Count participants by source and partition after joining local manifests.

    Window and normalised-data manifests share a participant key. These licensed
    input manifests stay local and are not distributed with the code.
    """
    windows = {
        Path(record["relative_path"]).stem: (
            Path(record["relative_path"]).parent.name.split("=", 1)[1],
            int(record["rows"]),
        )
        for record in json.loads(manifest.read_text())["records"]
    }
    sources = {
        Path(record["relative_path"]).stem:
            Path(record["relative_path"]).parent.name.split("=", 1)[1]
        for record in json.loads(normalized.read_text())["records"]
    }
    matched = set(windows) & set(sources)
    if len(matched) != len(windows):
        raise SystemExit(
            f"{len(windows) - len(matched)} of {len(windows)} participants in the "
            "window manifest are not in the normalized manifest; the join is not clean"
        )
    order = list(json.loads(profile.read_text())["sources"])
    rows, totals = [], {"train": 0, "calibration": 0, "selection": 0}
    grand = 0
    for source in order:
        counts = {"train": 0, "calibration": 0, "selection": 0}
        windows_here = 0
        for key in matched:
            if sources[key] != source:
                continue
            partition, rows_here = windows[key]
            counts[partition] += 1
            windows_here += rows_here
        for partition in totals:
            totals[partition] += counts[partition]
        grand += windows_here
        rows.append(
            f"{source} & {counts['train']} & {counts['calibration']} & "
            f"{counts['selection']} & {sum(counts.values())} & {windows_here:,} \\\\"
        )
    SPLIT_TOTALS.update(totals)
    SPLIT_TOTALS["participants"] = sum(totals.values())
    SPLIT_TOTALS["windows"] = grand
    rows.append(r"\midrule")
    rows.append(
        f"All development & {totals['train']} & {totals['calibration']} & "
        f"{totals['selection']} & {sum(totals.values())} & {grand:,} \\\\"
    )
    head = r"Source & Training & Calibration & Selection & Total & Window rows \\"
    caption = (
        "Analysed participants per development source across participant-disjoint "
        "training, "
        "calibration and selection partitions. Counts include the 1{,}020 participants "
        "with eligible windows, excluding 8 of the 1{,}028 enrolled participants. "
        "Participant assignments were fixed before overlapping windows were "
        "constructed. "
        "Window rows are summed over all three partitions, and each row carries both "
        "the 30- and 60-minute prediction horizons."
    )
    return table(rows, "lrrrrr", head, caption, "tab:split")


def main(argv: list[str] | None = None) -> int:
    root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--calibration-dir", type=Path, required=True)
    parser.add_argument("--profile", type=Path, required=True)
    parser.add_argument("--window-manifest", type=Path, required=True)
    parser.add_argument("--normalized-manifest", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, default=root / "manu" / "sections")
    parser.add_argument("--split-summary", type=Path, default=None)
    arguments = parser.parse_args(argv)

    written = {
        "tab_quality.tex": quality(arguments.calibration_dir),
        "tab_coverage.tex": coverage(arguments.profile),
        "tab_split.tex": split(arguments.profile, arguments.window_manifest,
                               arguments.normalized_manifest),
    }
    for name, text in written.items():
        (arguments.out_dir / name).write_text(text)
        print(f"wrote {arguments.out_dir / name}  {len(text.splitlines())} lines")

    # Figure 1 prints these three counts as hand-typed artwork. The table beside them is
    # generated and would move if the split ever did; the figure would not. Emitting the
    # totals lets the manuscript ledger bind both to one computation.
    if arguments.split_summary:
        arguments.split_summary.parent.mkdir(parents=True, exist_ok=True)
        arguments.split_summary.write_text(json.dumps(SPLIT_TOTALS, indent=1) + "\n")
        print(f"wrote {arguments.split_summary}  {SPLIT_TOTALS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
